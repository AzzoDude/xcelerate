def to_snake(name: str) -> str:
    name = name.replace("-", "_")
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"_+", "_", name).lower()
    if name in {
        "type", "match", "move", "ref", "self", "super", "crate", "fn", "impl",
        "struct", "enum", "let", "mut", "loop", "const", "static", "dyn", "async",
        "await", "where", "for", "in", "as", "use", "mod", "trait", "pub", "box",
        "abstract", "become", "do", "final", "macro", "override", "priv", "try",
        "typeof", "unsized", "virtual", "yield", "union",
    }:
        name += "_"
    return name


def to_upper_camel(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not out:
        out = "Value"
    if out[0].isdigit():
        out = "N" + out
    if out in ("Self", "Super", "Crate"):
        out += "Value"
    return out


def module_of(name: str) -> str:
    return name.split(".", 1)[0] if "." in name else ""


def module_ident(prefix: str) -> str:
    return MODULE_NAMES.get(prefix, prefix.lower())


def type_leaf(name: str) -> str:
    return name.split(".", 1)[1] if "." in name else name


# ---------------------------------------------------------------------------
# Type mapping
# ---------------------------------------------------------------------------

class Generator:
    def __init__(self, defs: dict[str, dict]):
        self.defs = defs
        self.commands = set()   # dotted names that are commands
        self.events = set()     # dotted names that are events

    # -- reference resolution ------------------------------------------------
    def map_ref(self, name: str) -> str | None:
        if name == "Extensible":
            return None
        if name in PRIMS:
            return PRIMS[name]
        if "." in name:
            module, leaf = name.split(".", 1)
            return f"crate::{module_ident(module)}::{leaf}"
        if name in self.defs or name in SKIP_ROOT or name in ("EmptyResult", "EmptyParams"):
            return f"crate::{name}"
        return None

    def rust_type(self, node: dict) -> str:
        kind = node["kind"]
        if kind == "prim":
            return PRIMS[node["name"]]
        if kind == "literal":
            return "String"
        if kind == "number":
            return "f64" if "." in node["value"] else "i64"
        if kind == "range":
            return "f64" if ("." in node["lo"] or "." in node["hi"]) else "u64"
        if kind == "ref":
            mapped = self.map_ref(node["name"])
            return mapped if mapped else "JsonValue"
        if kind == "array":
            inner = self.array_element(node)
            return f"Vec<{inner}>" if inner else "Vec<JsonValue>"
        # Inline maps, groups and unions collapse to a permissive JSON value.
        return "JsonValue"

    def array_element(self, node: dict) -> str | None:
        if len(node["members"]) != 1:
            return None
        member = node["members"][0]
        if member.get("drop"):
            return None
        return self.rust_type(member["value"])

    # -- definition emission -------------------------------------------------
    def field(self, member: dict) -> str | None:
        if member.get("drop") or member["key"] is None:
            return None
        value = member["value"]
        rust = self.rust_type(value)
        if member["optional"]:
            rust = f"Option<{rust}>"
        attrs = []
        if member["key"] != to_snake(member["key"]):
            attrs.append(f'rename = "{member["key"]}"')
        if member["optional"]:
            attrs.append('skip_serializing_if = "Option::is_none"')
        attr = f"    #[serde({', '.join(attrs)})]\n" if attrs else ""
        return f"{attr}    pub {to_snake(member['key'])}: {rust},"

    def emit_struct(self, name: str, node: dict) -> list[str]:
        lines = ["#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]",
                 '#[serde(rename_all = "camelCase")]',
                 f"pub struct {name} {{"]
        for member in node["members"]:
            if member.get("drop"):
                continue
            if member["key"] is None:
                # Group spread: `{ browsingContext.BaseInfo }` -> flatten.
                inner = self.rust_type(member["value"])
                if inner == "JsonValue":
                    continue
                field_name = to_snake(type_leaf(member["value"].get("name", "base")))
                lines.append("    #[serde(flatten)]")
                lines.append(f"    pub {field_name}: {inner},")
                continue
            rendered = self.field(member)
            if rendered:
                lines.append(rendered)
        lines.append("}")
        return lines

    def emit_string_enum(self, name: str, literals: list[str]) -> list[str]:
        lines = ["#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]",
                 f"pub enum {name} {{"]
        seen = set()
        for literal in literals:
            variant = to_upper_camel(literal)
            while variant in seen:
                variant += "Alt"
            seen.add(variant)
            lines.append(f'    #[serde(rename = "{literal}")]')
            lines.append(f"    {variant},")
        lines.append("}")
        return lines

    def emit_untagged_enum(self, name: str, refs: list[dict]) -> list[str]:
        lines = ["#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]",
                 "#[serde(untagged)]",
                 f"pub enum {name} {{"]
        seen = set()
        for ref in refs:
            rust = self.rust_type(ref)
            variant = to_upper_camel(type_leaf(ref.get("name", "value")))
            while variant in seen:
                variant += "Alt"
            seen.add(variant)
            lines.append(f"    {variant}({rust}),")
        lines.append("}")
        return lines

    def emit_alias(self, name: str, node: dict) -> list[str]:
        return [f"pub type {name} = {self.rust_type(node)};"]

    def classify(self, name: str, node: dict) -> list[str]:
        members = node.get("members")
        if node["kind"] == "map" and members is not None:
            real = [m for m in members if not m.get("drop")]
            if len(real) == 1 and real[0]["key"] is None:
                value = real[0]["value"]
                if value["kind"] == "union":
                    refs = refs_of(value)
                    if refs:
                        return self.emit_untagged_enum(name, refs)
                    return self.emit_alias(name, {"kind": "prim", "name": "any"})
                return self.emit_struct(name, node)
            return self.emit_struct(name, node)
        if node["kind"] == "group":
            keyed = [m for m in members if m.get("key") is not None]
            if keyed:
                return self.emit_struct(name, node)
            refs = collect_refs(node)
            if refs:
                return self.emit_untagged_enum(name, refs)
            return self.emit_alias(name, {"kind": "prim", "name": "any"})
        if node["kind"] == "union":
            if all(m["kind"] == "literal" for m in node["members"]):
                return self.emit_string_enum(name, [m["value"] for m in node["members"]])
            if all(m["kind"] == "ref" for m in node["members"]):
                return self.emit_untagged_enum(name, node["members"])
            return self.emit_alias(name, node)
        if node["kind"] == "literal":
            return self.emit_string_enum(name, [node["value"]])
        return self.emit_alias(name, node)

    # -- command / event discovery ------------------------------------------
    def discover(self) -> None:
        for name, node in self.defs.items():
            if name in SKIP_ROOT or node.get("kind") not in ("group", "union"):
                # Dispatch unions are parenthesised groups; the root `Command`
                # and `Event` are maps and must not be treated as one.
                continue
            if not name.endswith(("Command", "Event")):
                continue
            refs = [r["name"] for r in collect_refs(node)]
            if name.endswith("Command"):
                self.commands.update(refs)
            elif name.endswith("Event"):
                self.events.update(refs)

    def command_method(self, dotted: str) -> tuple[str, str, str]:
        node = self.defs.get(dotted)
        method = ""
        params = "crate::EmptyParams"
        if node:
            for member in node.get("members", []):
                if member.get("key") == "method":
                    method = member["value"].get("value", "")
                elif member.get("key") == "params":
                    mapped = self.rust_type(member["value"])
                    if mapped != "JsonValue":
                        params = mapped
        result_name = dotted + "Result"
        response = f"crate::{module_ident(module_of(result_name))}::{type_leaf(result_name)}"
        if result_name not in self.defs:
            response = "crate::EmptyResult"
        return method, params, response

    def event_method(self, dotted: str) -> tuple[str, str]:
        node = self.defs.get(dotted)
        method = ""
        params = "JsonValue"
        if node:
            for member in node.get("members", []):
                if member.get("key") == "method":
                    method = member["value"].get("value", "")
                elif member.get("key") == "params":
                    mapped = self.rust_type(member["value"])
                    params = mapped if mapped != "JsonValue" else "JsonValue"
        return method, params

    def emit_command(self, dotted: str) -> list[str]:
        method, params, response = self.command_method(dotted)
        name = type_leaf(dotted)
        return [
            f"/// `{method}`",
            f"pub struct {name};",
            f"impl crate::BidiCommand for {name} {{",
            f'    const METHOD: &\'static str = "{method}";',
            f"    type Params = {params};",
            f"    type Response = {response};",
            "}",
        ]

    def emit_event(self, dotted: str) -> list[str]:
        method, params = self.event_method(dotted)
        name = type_leaf(dotted)
        return [
            f"/// `{method}`",
            f"pub struct {name};",
            f"impl crate::BidiEvent for {name} {{",
            f'    const METHOD: &\'static str = "{method}";',
            f"    type Params = {params};",
            "}",
        ]


