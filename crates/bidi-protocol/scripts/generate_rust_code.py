#!/usr/bin/env python3
"""Generate Rust types for the W3C WebDriver BiDi protocol.

Mirrors the `browser-protocol` generator's pipeline, but the harvest source is
different: Chrome DevTools Protocol ships a machine-readable JSON from Google
(`browser_protocol.json` / `js_protocol.json`), whereas WebDriver BiDi only ships
its definitions as *CDDL* embedded in the Bikeshed specification (`index.bs`).

Pipeline
--------
1. Download `index.bs` from the w3c/webdriver-bidi repository (or read a local
   copy with ``--spec``).
2. Extract every ``<pre class="cddl ...">`` block and concatenate them into a
   single ``all.cddl`` document (this is exactly what the W3C's own
   ``scripts/cddl/generate.js`` does, and what Google feeds to ``cddlconv`` to
   produce ``webdriver-bidi-protocol``).
3. Parse the CDDL into a small AST of definitions.
4. Emit one Rust module per BiDi module (``browsingContext`` -> ``browsing_context``)
   plus the root envelope in ``src/lib.rs``.

Usage
-----
    python scripts/generate_rust_code.py            # download + generate
    python scripts/generate_rust_code.py --spec path/to/index.bs
    python scripts/generate_rust_code.py --check     # exit 1 if the spec changed
"""

