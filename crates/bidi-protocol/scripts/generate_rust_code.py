def is_dispatch_union(name: str, node: dict) -> bool:
    """A module-level `<Module>Command` / `<Module>Result` / `<Module>Event` union.

    These have no dotted prefix (e.g. `BrowsingContextResult`); dotted unions such
    as `script.EvaluateResult` are real types and must be generated.
    """
    if "." in name:
        return False
    if not name.endswith(("Command", "Result", "Event")):
        return False
    if node["kind"] not in ("group", "union", "map"):
        return False
    return bool(collect_refs(node))


def generate(cddl: str) -> None:
    definitions = split_definitions(normalize_commas(cddl))
    defs: dict[str, dict] = {}
    for name, rhs in definitions:
        try:
            defs[name] = Parser(lex(rhs)).parse()
        except Exception as error:  # noqa: BLE001 - tolerate spec irregularities
            print(f"  ! skipped {name}: {error}")

    gen = Generator(defs)
    gen.discover()

    modules: dict[str, list[str]] = {}
    root: list[str] = []

    for name in sorted(defs):
        if name in SKIP_ROOT:
            continue
        if name in gen.commands or name in gen.events:
            # Command/event groups become marker structs below.
            continue
        node = defs[name]
        if is_dispatch_union(name, node):
            continue
        try:
            emitted = gen.classify(type_leaf(name), node)
        except Exception as error:  # noqa: BLE001
            print(f"  ! failed {name}: {error}")
            continue
        target = root if module_of(name) == "" else modules.setdefault(module_ident(module_of(name)), [])
        target.append(f"/// `{name}`")
        target.extend(emitted)
        target.append("")

    # Command / event marker impls, grouped by module.
    for dotted in sorted(gen.commands):
        if dotted not in defs:
            continue
        module = module_ident(module_of(dotted)) or "root"
        bucket = root if module == "root" else modules.setdefault(module, [])
        bucket.extend(gen.emit_command(dotted))
        bucket.append("")

    for dotted in sorted(gen.events):
        if dotted not in defs:
            continue
        module = module_ident(module_of(dotted)) or "root"
        bucket = root if module == "root" else modules.setdefault(module, [])
        bucket.extend(gen.emit_event(dotted))
        bucket.append("")

    os.makedirs(SRC, exist_ok=True)
    for module in sorted(modules):
        write_module(module, modules[module])

    write_lib(sorted(modules), root)
    print(f"generated {len(defs)} definitions into {len(modules)} modules + root")


def write_module(module: str, body: list[str]) -> None:
    directory = os.path.join(SRC, module)
    os.makedirs(directory, exist_ok=True)
    header = [
        "// @generated by scripts/generate_rust_code.py -- do not edit by hand.",
        "#![allow(non_snake_case, unused_imports, dead_code, clippy::all)]",
        "",
        "use serde::{Deserialize, Serialize};",
        "use serde_json::Value as JsonValue;",
        "use crate::{BidiCommand, BidiEvent};",
        "",
    ]
    with open(os.path.join(directory, "mod.rs"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(header + body) + "\n")


def write_lib(modules: list[str], root: list[str]) -> None:
    declarations = [f"pub mod {module};" for module in modules]
    content = "\n".join([PROLOGUE, "", "\n".join(declarations), "", "\n".join(root)]) + "\n"
    with open(os.path.join(SRC, "lib.rs"), "w", encoding="utf-8") as handle:
        handle.write(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", help="path to a local index.bs (defaults to downloading)")
    parser.add_argument("--cddl", help="regenerate from a local all.cddl (skips extraction)")
    parser.add_argument("--check", action="store_true", help="exit 1 if the remote spec differs")
    args = parser.parse_args()

    if args.check:
        current = open(SPEC_FILE, encoding="utf-8").read() if os.path.exists(SPEC_FILE) else ""
        sys.exit(0 if current == fetch(SPEC_URL) else 1)

    if args.cddl:
        cddl = open(args.cddl, encoding="utf-8").read()
        print(f"regenerating from {args.cddl}")
        generate(cddl)
        return

    if args.spec:
        html = open(args.spec, encoding="utf-8").read()
        spec_path = args.spec
    else:
        html = fetch(SPEC_URL)
        with open(SPEC_FILE, "w", encoding="utf-8") as handle:
            handle.write(html)
        spec_path = SPEC_FILE

    cddl = extract_cddl(html)
    with open(CDDL_FILE, "w", encoding="utf-8") as handle:
        handle.write(cddl)
    print(f"harvested CDDL from {spec_path} -> {CDDL_FILE}")
    generate(cddl)


if __name__ == "__main__":
    main()
